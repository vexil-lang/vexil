//! TypeScript code generation backend for the Vexil schema compiler.
//!
//! Generates TypeScript interfaces and encode/decode functions that use
//! the `@vexil-lang/runtime` npm package for wire I/O.

/// TypeScript [`CodegenBackend`](backend::TypeScriptBackend) implementation.
pub mod backend;
/// Delta encoder/decoder class generation for messages with `@delta` fields.
pub mod delta;
/// Low-level [`CodeWriter`] helper for emitting indented TypeScript source.
pub mod emit;
/// Enum type generation: string literal union + const object + encode/decode.
pub mod enum_gen;
/// Flags type generation: number type alias + named bit constants + encode/decode.
pub mod flags;
/// Portable trait-function body generation.
pub mod fn_body;
/// Message and config type generation: interface + encode/decode functions.
pub mod message;
/// Newtype (wrapper) generation: type alias + encode/decode delegation.
pub mod newtype;
/// Field-only trait and implementation proof generation.
pub mod trait_gen;
/// TypeScript type mapping utilities for Vexil resolved types.
pub mod types;
/// Union (tagged-discriminant) generation: discriminated union + encode/decode.
pub mod union_gen;

/// Re-export of the TypeScript code-generation backend.
pub use backend::TypeScriptBackend;

use std::collections::HashMap;

use vexil_lang::codegen::portable::PortableFunction;
use vexil_lang::ir::{CompiledSchema, ResolvedType, TypeDef, TypeId};

/// Errors that can occur during TypeScript code generation.
#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum CodegenError {
    #[error("unresolved type {type_id:?} referenced by {referenced_by}")]
    UnresolvedType {
        type_id: vexil_lang::ir::TypeId,
        referenced_by: String,
    },
    #[error(transparent)]
    PortableFunction(#[from] vexil_lang::codegen::portable::PortableFunctionError),
    #[error("TypeScript identifier collision for '{name}': {context}")]
    IdentifierCollision { name: String, context: String },
}

/// Generate TypeScript code for a compiled schema (no cross-file imports).
pub fn generate(compiled: &CompiledSchema) -> Result<String, CodegenError> {
    generate_with_imports(compiled, None)
}

/// Generate TypeScript code for a compiled schema, with optional cross-file import statements.
///
/// `import_paths` maps type names to their module paths for cross-file imports.
pub(crate) fn generate_with_imports(
    compiled: &CompiledSchema,
    import_paths: Option<&std::collections::HashMap<String, String>>,
) -> Result<String, CodegenError> {
    let impl_functions = prepare_trait_functions(compiled)?;

    // Emit declarations first so their structural requirements can drive the
    // runtime import without scanning generated source text.
    let declarations = emit_declarations(compiled, &impl_functions)?;
    let mut w = emit::CodeWriter::new();

    // Header
    w.line("// Code generated by vexilc. DO NOT EDIT.");
    let ns = compiled.namespace.join(".");
    w.line(&format!("// Source: {ns}"));

    let mut emitted_import = false;

    // Runtime import — omitted entirely when no codec is emitted.
    let runtime_imports = declarations.runtime_imports.symbols();
    if !runtime_imports.is_empty() {
        w.blank();
        w.line(&format!(
            "import {{ {} }} from '@vexil-lang/runtime';",
            runtime_imports.join(", ")
        ));
        emitted_import = true;
    }

    // Cross-file imports
    if let Some(paths) = import_paths {
        let mut imports: Vec<(&String, &String)> = paths.iter().collect();
        imports.sort_by_key(|(name, _)| (*name).clone());
        for (type_name, module_path) in imports {
            if !emitted_import {
                w.blank();
                emitted_import = true;
            }
            let is_trait = compiled.registry.iter().any(|(_, def)| {
                matches!(def, TypeDef::Trait(trait_def) if trait_def.name == type_name.as_str())
            });
            if is_trait {
                w.line(&format!("import {{ {type_name} }} from '{module_path}';"));
            } else {
                w.line(&format!(
                    "import {{ {type_name}, encode{type_name}, decode{type_name} }} from '{module_path}';",
                ));
            }
        }
    }
    w.blank();

    // Schema hash
    let hash = vexil_lang::canonical::schema_hash(compiled);
    let hash_str = hash
        .iter()
        .map(|b| format!("0x{b:02x}"))
        .collect::<Vec<_>>()
        .join(", ");
    w.line(&format!(
        "export const SCHEMA_HASH = new Uint8Array([{hash_str}]);"
    ));

    // Schema version
    if let Some(ref version) = compiled.annotations.version {
        w.line(&format!("export const SCHEMA_VERSION = '{version}';"));
    }

    if compiled.impls().next().is_some() {
        w.blank();
        w.line("type _VexilAssertAssignable<T extends U, U> = T;");
    }

    Ok(format!("{}{}", w.finish(), declarations.code))
}

#[derive(Default)]
struct RuntimeImports {
    bit_reader: bool,
    bit_writer: bool,
}

impl RuntimeImports {
    fn require_codec(&mut self) {
        self.bit_reader = true;
        self.bit_writer = true;
    }

    fn symbols(&self) -> Vec<&'static str> {
        let mut symbols = Vec::new();
        if self.bit_reader {
            symbols.push("BitReader");
        }
        if self.bit_writer {
            symbols.push("BitWriter");
        }
        symbols
    }
}

struct EmittedDeclarations {
    code: String,
    runtime_imports: RuntimeImports,
}

/// Emit the body: one section per declared type, then any impl assertions.
///
/// Produced before the header so declaration structure can drive imports.
fn emit_declarations(
    compiled: &CompiledSchema,
    impl_functions: &HashMap<TypeId, Vec<PortableFunction>>,
) -> Result<EmittedDeclarations, CodegenError> {
    let mut w = emit::CodeWriter::new();
    let mut runtime_imports = RuntimeImports::default();

    for &type_id in &compiled.declarations {
        let typedef =
            compiled
                .registry
                .get(type_id)
                .ok_or_else(|| CodegenError::UnresolvedType {
                    type_id,
                    referenced_by: "declarations".to_string(),
                })?;

        w.blank();
        let type_name = type_name_of(typedef);
        w.line(&format!("// \u{2500}\u{2500} {type_name} \u{2500}\u{2500}"));

        match typedef {
            TypeDef::Message(msg) => {
                runtime_imports.require_codec();
                let functions = impl_functions
                    .get(&type_id)
                    .map(Vec::as_slice)
                    .unwrap_or_default();
                message::emit_message(&mut w, msg, &compiled.registry, functions);
                delta::emit_delta(&mut w, msg, &compiled.registry);
            }
            TypeDef::Enum(en) => {
                runtime_imports.require_codec();
                enum_gen::emit_enum(&mut w, en, &compiled.registry);
            }
            TypeDef::Flags(fl) => {
                runtime_imports.require_codec();
                flags::emit_flags(&mut w, fl, &compiled.registry);
            }
            TypeDef::Union(un) => {
                runtime_imports.require_codec();
                union_gen::emit_union(&mut w, un, &compiled.registry);
            }
            TypeDef::Newtype(nt) => {
                runtime_imports.require_codec();
                newtype::emit_newtype(&mut w, nt, &compiled.registry);
            }
            TypeDef::Config(cfg) => {
                message::emit_config(&mut w, cfg, &compiled.registry);
            }
            TypeDef::Trait(trait_def) => {
                trait_gen::emit_trait(&mut w, type_id, trait_def, compiled)?
            }
            _ => {} // non_exhaustive guard
        }
    }

    for (_, impl_def) in compiled.impls() {
        w.blank();
        trait_gen::emit_impl_assertion(&mut w, impl_def, &compiled.registry);
    }

    Ok(EmittedDeclarations {
        code: w.finish(),
        runtime_imports,
    })
}

/// Returns the name of a TypeDef for use in section separator comments.
pub(crate) fn type_name_of(typedef: &TypeDef) -> &str {
    match typedef {
        TypeDef::Message(m) => m.name.as_str(),
        TypeDef::Enum(e) => e.name.as_str(),
        TypeDef::Flags(f) => f.name.as_str(),
        TypeDef::Union(u) => u.name.as_str(),
        TypeDef::Newtype(n) => n.name.as_str(),
        TypeDef::Config(c) => c.name.as_str(),
        TypeDef::Trait(t) => t.name.as_str(),
        _ => "Unknown",
    }
}

fn prepare_trait_functions(
    compiled: &CompiledSchema,
) -> Result<HashMap<TypeId, Vec<PortableFunction>>, CodegenError> {
    for &type_id in &compiled.declarations {
        let Some(TypeDef::Trait(trait_def)) = compiled.registry.get(type_id) else {
            continue;
        };
        for function in vexil_lang::codegen::portable::trait_signatures(compiled, type_id)? {
            if trait_def
                .fields
                .iter()
                .any(|field| field.name == function.name)
            {
                return Err(CodegenError::IdentifierCollision {
                    name: function.name.to_string(),
                    context: "trait function conflicts with a generated field member".to_string(),
                });
            }
            reject_typescript_keyword(function.name.as_str(), "trait function")?;
            for parameter in &function.params {
                reject_typescript_keyword(parameter.name.as_str(), "function parameter")?;
            }
        }
    }

    let mut by_target: HashMap<TypeId, Vec<PortableFunction>> = HashMap::new();
    for (_, impl_def) in compiled.impls() {
        let ResolvedType::Named(target_id) = &impl_def.target_type else {
            continue;
        };
        let message = match compiled.registry.get(*target_id) {
            Some(TypeDef::Message(message)) => message,
            _ => continue,
        };
        for function in vexil_lang::codegen::portable::project_impl(compiled, impl_def)? {
            if message
                .fields
                .iter()
                .any(|field| field.name == function.name)
                || matches!(function.name.as_str(), "encode" | "decode")
            {
                return Err(CodegenError::IdentifierCollision {
                    name: function.name.to_string(),
                    context: "trait method conflicts with a generated TypeScript member"
                        .to_string(),
                });
            }
            reject_typescript_keyword(function.name.as_str(), "trait method")?;
            let functions = by_target.entry(*target_id).or_default();
            if functions
                .iter()
                .any(|existing| existing.name == function.name)
            {
                return Err(CodegenError::IdentifierCollision {
                    name: function.name.to_string(),
                    context: "multiple implemented traits project the same method".to_string(),
                });
            }
            for parameter in &function.params {
                reject_typescript_keyword(parameter.name.as_str(), "function parameter")?;
            }
            for statement in &function.statements {
                if let vexil_lang::codegen::portable::PortableStatement::Let { name, .. } =
                    statement
                {
                    reject_typescript_keyword(name.as_str(), "local binding")?;
                }
            }
            functions.push(function);
        }
    }
    Ok(by_target)
}

fn reject_typescript_keyword(name: &str, subject: &str) -> Result<(), CodegenError> {
    if is_typescript_keyword(name) {
        Err(CodegenError::IdentifierCollision {
            name: name.to_string(),
            context: format!("{subject} is a reserved TypeScript keyword"),
        })
    } else {
        Ok(())
    }
}

fn is_typescript_keyword(name: &str) -> bool {
    matches!(
        name,
        "break"
            | "case"
            | "catch"
            | "class"
            | "const"
            | "continue"
            | "debugger"
            | "default"
            | "delete"
            | "do"
            | "else"
            | "enum"
            | "export"
            | "extends"
            | "false"
            | "finally"
            | "for"
            | "function"
            | "if"
            | "import"
            | "in"
            | "instanceof"
            | "new"
            | "null"
            | "return"
            | "super"
            | "switch"
            | "this"
            | "throw"
            | "true"
            | "try"
            | "typeof"
            | "var"
            | "void"
            | "while"
            | "with"
            | "as"
            | "implements"
            | "interface"
            | "let"
            | "package"
            | "private"
            | "protected"
            | "public"
            | "static"
            | "yield"
            | "any"
            | "boolean"
            | "constructor"
            | "declare"
            | "get"
            | "module"
            | "require"
            | "number"
            | "set"
            | "string"
            | "symbol"
            | "type"
            | "from"
            | "of"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generate_produces_output() {
        let result = vexil_lang::compile("namespace test.gen\nmessage Foo { x @0 : u32 }");
        let compiled = result.compiled.unwrap();
        let code = generate(&compiled).unwrap();
        assert!(code.contains("export interface Foo"));
        assert!(code.contains("export function encodeFoo"));
        assert!(code.contains("export function decodeFoo"));
        assert!(code.contains("import { BitReader, BitWriter } from '@vexil-lang/runtime'"));
    }

    #[test]
    fn generate_with_no_imports_matches_generate() {
        let result = vexil_lang::compile("namespace test.gen\nmessage Foo { x @0 : u32 }");
        let compiled = result.compiled.unwrap();
        let without = generate(&compiled).unwrap();
        let with = generate_with_imports(&compiled, None).unwrap();
        assert_eq!(without, with);
    }

    #[test]
    fn ts_backend_generate_matches_free_function() {
        use vexil_lang::codegen::CodegenBackend;
        let result = vexil_lang::compile("namespace test.backend\nmessage Foo { x @0 : u32 }");
        let compiled = result.compiled.unwrap();
        let free_fn = generate(&compiled).unwrap();
        let backend = crate::backend::TypeScriptBackend;
        let trait_fn = backend.generate(&compiled).unwrap();
        assert_eq!(free_fn, trait_fn);
    }

    #[test]
    fn emits_function_bearing_traits() {
        let compiled = vexil_lang::compile(
            "namespace test.function_trait\ntrait Validatable {\n    fn validate() -> bool\n}",
        )
        .compiled
        .unwrap();
        let generated = generate(&compiled).expect("function signature generates");
        assert!(generated.contains("validate(): boolean;"));
    }

    #[test]
    fn rejects_trait_function_member_collisions() {
        let compiled = vexil_lang::compile(
            "namespace test.collision\ntrait Conflicting { value @0 : i32 fn value() -> i32 }",
        )
        .compiled
        .unwrap();
        assert!(matches!(
            generate(&compiled),
            Err(CodegenError::IdentifierCollision { .. })
        ));
    }

    #[test]
    fn rejects_nonportable_calls_at_codegen_boundary() {
        let compiled = vexil_lang::compile(
            "namespace test.call\ntrait Validatable { fn validate() -> bool }\nmessage Event { value @0 : bool }\nimpl Validatable for Event { fn validate() -> bool { return helper() } }",
        )
        .compiled
        .unwrap();
        assert!(matches!(
            generate(&compiled),
            Err(CodegenError::PortableFunction(
                vexil_lang::codegen::portable::PortableFunctionError::UnsupportedCall { .. }
            ))
        ));
    }

    #[test]
    fn project_codegen_imports_trait_without_codec_symbols() {
        use vexil_lang::codegen::CodegenBackend;
        use vexil_lang::resolve::InMemoryLoader;

        let root_src = "namespace proj.root\nimport { Tagged } from proj.dep\nmessage Event { tag @0 : u64 }\nimpl Tagged<u64> for Event { fn retag(tag: u64) -> u64 { self.tag = tag return self.tag } }";
        let dep_src = "namespace proj.dep\ntrait Tagged<T> { tag @0 : T fn retag(tag: T) -> T }";
        let mut loader = InMemoryLoader::new();
        loader.schemas.insert("proj.dep".into(), dep_src.into());
        let result = vexil_lang::compile_project(
            root_src,
            &std::path::PathBuf::from("proj/root.vexil"),
            &loader,
        )
        .unwrap();
        assert!(result.diagnostics.is_empty(), "{:?}", result.diagnostics);

        let files = crate::backend::TypeScriptBackend
            .generate_project(&result)
            .unwrap();
        let root = files
            .iter()
            .find(|(path, _)| path.to_string_lossy().ends_with("root.ts"))
            .map(|(_, code)| code)
            .unwrap();
        assert!(root.contains("import { Tagged } from './dep';"), "{root}");
        assert!(!root.contains("encodeTagged"), "{root}");
        assert!(root.contains("retag(tag: bigint): bigint"), "{root}");
    }
}
