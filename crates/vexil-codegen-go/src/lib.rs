//! Go code generation backend for the Vexil schema compiler.
//!
//! Generates Go structs implementing the `Packer`/`Unpacker` interfaces
//! from the `github.com/vexil-lang/vexil/packages/runtime-go` module.

pub mod backend;
pub mod delta;
pub mod emit;
pub mod enum_gen;
pub mod flags;
pub mod fn_body;
pub mod message;
pub mod newtype;
pub mod trait_gen;
pub mod types;
pub mod union_gen;

pub use backend::GoBackend;

use vexil_lang::ir::{CompiledSchema, ResolvedType, TypeDef};

#[derive(Debug, Clone, PartialEq, thiserror::Error)]
pub enum CodegenError {
    #[error("unresolved type {type_id:?} referenced by {referenced_by}")]
    UnresolvedType {
        type_id: vexil_lang::ir::TypeId,
        referenced_by: String,
    },
    #[error(transparent)]
    PortableFunction(#[from] vexil_lang::codegen::portable::PortableFunctionError),
    #[error("Go identifier collision for '{name}': {context}")]
    IdentifierCollision { name: String, context: String },
}

/// Generate Go code for a compiled schema (no cross-file imports).
pub fn generate(compiled: &CompiledSchema) -> Result<String, CodegenError> {
    generate_with_imports(compiled, None)
}

/// Generate Go code for a compiled schema, with optional cross-file import information.
///
/// `import_types` maps type names that are imported from other packages.
pub(crate) fn generate_with_imports(
    compiled: &CompiledSchema,
    import_types: Option<&std::collections::HashMap<String, String>>,
) -> Result<String, CodegenError> {
    preflight_trait_functions(compiled)?;
    let mut w = emit::CodeWriter::new();

    // Header
    w.line("// Code generated by vexilc. DO NOT EDIT.");
    let ns = compiled.namespace.join(".");
    w.line(&format!("// Source: {ns}"));
    w.blank();

    // Package declaration — last segment of namespace
    let pkg = compiled
        .namespace
        .last()
        .map(|s| s.as_str())
        .unwrap_or("main");
    w.line(&format!("package {pkg}"));
    w.blank();

    // Import block
    let has_codecs = compiled.declarations.iter().any(|&id| {
        compiled
            .registry
            .get(id)
            .is_some_and(|td| !matches!(td, TypeDef::Config(_) | TypeDef::Trait(_)))
    });

    let has_unions = compiled.declarations.iter().any(|&id| {
        compiled
            .registry
            .get(id)
            .is_some_and(|td| matches!(td, TypeDef::Union(_)))
    });

    // Check if we need cross-package imports
    let has_cross_imports = import_types.is_some_and(|m| !m.is_empty());

    let needs_fmt = has_unions
        || compiled.declarations.iter().any(|&id| {
            compiled
                .registry
                .get(id)
                .is_some_and(type_def_has_constraints)
        });
    let needs_sort = compiled.declarations.iter().any(|&id| {
        compiled
            .registry
            .get(id)
            .is_some_and(type_def_has_ordered_collection)
    });
    let needs_grouped = has_cross_imports || (has_codecs && (needs_fmt || needs_sort));

    if has_codecs || has_cross_imports {
        if needs_grouped {
            w.line("import (");
            w.indent();
            if needs_fmt {
                w.line("\"fmt\"");
            }
            if needs_sort {
                w.line("\"sort\"");
            }
            if has_codecs {
                w.blank();
                w.line("vexil \"github.com/vexil-lang/vexil/packages/runtime-go\"");
            }
            if let Some(imports) = import_types {
                let mut paths: Vec<&String> = imports.values().collect();
                paths.sort();
                paths.dedup();
                for path in paths {
                    w.line(&format!("\"{path}\""));
                }
            }
            w.dedent();
            w.line(")");
        } else if has_codecs {
            w.line("import vexil \"github.com/vexil-lang/vexil/packages/runtime-go\"");
        }
        w.blank();
    }

    // Schema hash
    let hash = vexil_lang::canonical::schema_hash(compiled);
    let hash_str = hash
        .iter()
        .map(|b| format!("0x{b:02x}"))
        .collect::<Vec<_>>()
        .join(", ");
    w.line(&format!("var SchemaHash = [32]byte{{{hash_str}}}"));

    // Schema version
    if let Some(ref version) = compiled.annotations.version {
        w.line(&format!("const SchemaVersion = \"{version}\""));
    }

    let mut constants: Vec<_> = compiled.constants.iter().collect();
    constants.sort_by_key(|(name, _)| name.as_str());
    for (name, value) in constants {
        w.line(&format!("const {name} = {}", value.value));
    }

    // Emit each declared type
    for &type_id in &compiled.declarations {
        let typedef =
            compiled
                .registry
                .get(type_id)
                .ok_or_else(|| CodegenError::UnresolvedType {
                    type_id,
                    referenced_by: "declarations".to_string(),
                })?;

        w.blank();
        let type_name = type_name_of(typedef);
        w.line(&format!("// \u{2500}\u{2500} {type_name} \u{2500}\u{2500}"));

        match typedef {
            TypeDef::Message(msg) => {
                message::emit_message(&mut w, msg, &compiled.registry);
                delta::emit_delta(&mut w, msg, &compiled.registry);
            }
            TypeDef::Enum(en) => {
                enum_gen::emit_enum(&mut w, en, &compiled.registry);
            }
            TypeDef::Flags(fl) => {
                flags::emit_flags(&mut w, fl, &compiled.registry);
            }
            TypeDef::Union(un) => {
                union_gen::emit_union(&mut w, un, &compiled.registry);
            }
            TypeDef::Newtype(nt) => {
                newtype::emit_newtype(&mut w, nt, &compiled.registry);
            }
            TypeDef::Config(cfg) => {
                message::emit_config(&mut w, cfg, &compiled.registry);
            }
            TypeDef::Trait(trait_def) => {
                trait_gen::emit_trait(&mut w, type_id, trait_def, compiled, import_types)?
            }
            _ => {} // non_exhaustive guard
        }
    }

    for (_, impl_def) in compiled.impls() {
        w.blank();
        trait_gen::emit_impl(&mut w, impl_def, compiled, import_types)?;
    }

    Ok(w.finish())
}

fn type_def_has_ordered_collection(type_def: &TypeDef) -> bool {
    fn contains_ordered_collection(ty: &ResolvedType) -> bool {
        match ty {
            ResolvedType::Map(_, _) | ResolvedType::Set(_) => true,
            ResolvedType::Optional(inner)
            | ResolvedType::Array(inner)
            | ResolvedType::FixedArray(inner, _)
            | ResolvedType::Vec2(inner)
            | ResolvedType::Vec3(inner)
            | ResolvedType::Vec4(inner)
            | ResolvedType::Quat(inner)
            | ResolvedType::Mat3(inner)
            | ResolvedType::Mat4(inner) => contains_ordered_collection(inner),
            ResolvedType::Result(ok, err) => {
                contains_ordered_collection(ok) || contains_ordered_collection(err)
            }
            _ => false,
        }
    }

    match type_def {
        TypeDef::Message(message) => message
            .fields
            .iter()
            .any(|field| contains_ordered_collection(&field.resolved_type)),
        TypeDef::Union(union) => union
            .variants
            .iter()
            .flat_map(|variant| &variant.fields)
            .any(|field| contains_ordered_collection(&field.resolved_type)),
        TypeDef::Newtype(newtype) => contains_ordered_collection(&newtype.inner_type),
        TypeDef::Config(config) => config
            .fields
            .iter()
            .any(|field| contains_ordered_collection(&field.resolved_type)),
        TypeDef::Trait(trait_def) => trait_def
            .fields
            .iter()
            .any(|field| contains_ordered_collection(&field.ty)),
        _ => false,
    }
}

fn type_def_has_constraints(type_def: &TypeDef) -> bool {
    match type_def {
        TypeDef::Message(message) => message
            .fields
            .iter()
            .any(|field| field.constraint.is_some()),
        TypeDef::Union(union) => union
            .variants
            .iter()
            .flat_map(|variant| &variant.fields)
            .any(|field| field.constraint.is_some()),
        _ => false,
    }
}

/// Returns the name of a TypeDef for use in section separator comments.
pub(crate) fn type_name_of(typedef: &TypeDef) -> &str {
    match typedef {
        TypeDef::Message(m) => m.name.as_str(),
        TypeDef::Enum(e) => e.name.as_str(),
        TypeDef::Flags(f) => f.name.as_str(),
        TypeDef::Union(u) => u.name.as_str(),
        TypeDef::Newtype(n) => n.name.as_str(),
        TypeDef::Config(c) => c.name.as_str(),
        TypeDef::Trait(t) => t.name.as_str(),
        _ => "Unknown",
    }
}

fn preflight_trait_functions(compiled: &CompiledSchema) -> Result<(), CodegenError> {
    for &type_id in &compiled.declarations {
        let Some(TypeDef::Trait(trait_def)) = compiled.registry.get(type_id) else {
            continue;
        };
        let mut methods = Vec::new();
        for function in vexil_lang::codegen::portable::trait_signatures(compiled, type_id)? {
            let method = crate::types::to_pascal_case(function.name.as_str());
            let conflicts_with_field = trait_def.fields.iter().any(|field| {
                let field_name = crate::types::to_pascal_case(field.name.as_str());
                method == field_name || method == format!("Get{field_name}")
            });
            if conflicts_with_field || methods.contains(&method) {
                return Err(CodegenError::IdentifierCollision {
                    name: method,
                    context: "trait function conflicts with another generated Go member"
                        .to_string(),
                });
            }
            methods.push(method);
            for parameter in &function.params {
                reject_go_keyword(parameter.name.as_str(), "function parameter")?;
            }
        }
    }

    let mut target_methods: std::collections::HashMap<vexil_lang::ir::TypeId, Vec<String>> =
        std::collections::HashMap::new();
    for (_, impl_def) in compiled.impls() {
        let functions = vexil_lang::codegen::portable::project_impl(compiled, impl_def)?;
        let message = match &impl_def.target_type {
            vexil_lang::ir::ResolvedType::Named(id) => match compiled.registry.get(*id) {
                Some(TypeDef::Message(message)) => (*id, message),
                _ => continue,
            },
            _ => continue,
        };
        for function in functions {
            let method = crate::types::to_pascal_case(function.name.as_str());
            let conflicts_with_field = message.1.fields.iter().any(|field| {
                let field_name = crate::types::to_pascal_case(field.name.as_str());
                method == field_name || method == format!("Get{field_name}")
            });
            if conflicts_with_field || matches!(method.as_str(), "Pack" | "Unpack") {
                return Err(CodegenError::IdentifierCollision {
                    name: method,
                    context: "trait method conflicts with a generated Go member".to_string(),
                });
            }
            let methods = target_methods.entry(message.0).or_default();
            if methods.contains(&method) {
                return Err(CodegenError::IdentifierCollision {
                    name: method,
                    context: "multiple implemented traits project the same Go method".to_string(),
                });
            }
            methods.push(method);
            for parameter in &function.params {
                reject_go_binding(parameter.name.as_str(), "function parameter")?;
            }
            for statement in &function.statements {
                if let vexil_lang::codegen::portable::PortableStatement::Let { name, .. } =
                    statement
                {
                    reject_go_binding(name.as_str(), "local binding")?;
                }
            }
        }
    }
    Ok(())
}

fn reject_go_keyword(name: &str, subject: &str) -> Result<(), CodegenError> {
    if is_go_keyword(name) {
        Err(CodegenError::IdentifierCollision {
            name: name.to_string(),
            context: format!("{subject} is a reserved Go keyword"),
        })
    } else {
        Ok(())
    }
}

fn reject_go_binding(name: &str, subject: &str) -> Result<(), CodegenError> {
    reject_go_keyword(name, subject)?;
    if name == "m" {
        Err(CodegenError::IdentifierCollision {
            name: name.to_string(),
            context: format!("{subject} conflicts with the generated Go receiver"),
        })
    } else {
        Ok(())
    }
}

fn is_go_keyword(name: &str) -> bool {
    matches!(
        name,
        "break"
            | "default"
            | "func"
            | "interface"
            | "select"
            | "case"
            | "defer"
            | "go"
            | "map"
            | "struct"
            | "chan"
            | "else"
            | "goto"
            | "package"
            | "switch"
            | "const"
            | "fallthrough"
            | "if"
            | "range"
            | "type"
            | "continue"
            | "for"
            | "import"
            | "return"
            | "var"
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generate_produces_output() {
        let result = vexil_lang::compile("namespace test.gen\nmessage Foo { x @0 : u32 }");
        let compiled = result.compiled.unwrap();
        let code = generate(&compiled).unwrap();
        assert!(code.contains("type Foo struct"));
        assert!(code.contains("func (m *Foo) Pack"));
        assert!(code.contains("func (m *Foo) Unpack"));
        assert!(code.contains("package gen"));
    }

    #[test]
    fn generate_with_no_imports_matches_generate() {
        let result = vexil_lang::compile("namespace test.gen\nmessage Foo { x @0 : u32 }");
        let compiled = result.compiled.unwrap();
        let without = generate(&compiled).unwrap();
        let with = generate_with_imports(&compiled, None).unwrap();
        assert_eq!(without, with);
    }

    #[test]
    fn go_backend_generate_matches_free_function() {
        use vexil_lang::codegen::CodegenBackend;
        let result = vexil_lang::compile("namespace test.backend\nmessage Foo { x @0 : u32 }");
        let compiled = result.compiled.unwrap();
        let free_fn = generate(&compiled).unwrap();
        let backend = crate::backend::GoBackend;
        let trait_fn = backend.generate(&compiled).unwrap();
        assert_eq!(free_fn, trait_fn);
    }

    #[test]
    fn emits_function_bearing_traits() {
        let compiled = vexil_lang::compile(
            "namespace test.function_trait\ntrait Validatable {\n    fn validate() -> bool\n}",
        )
        .compiled
        .unwrap();
        let generated = generate(&compiled).expect("function signature generates");
        assert!(generated.contains("Validate() bool"));
    }

    #[test]
    fn rejects_trait_function_member_collisions() {
        let compiled = vexil_lang::compile(
            "namespace test.collision\ntrait Conflicting { value @0 : i32 fn value() -> i32 }",
        )
        .compiled
        .unwrap();
        assert!(matches!(
            generate(&compiled),
            Err(CodegenError::IdentifierCollision { .. })
        ));
    }

    #[test]
    fn rejects_nonportable_calls_at_codegen_boundary() {
        let compiled = vexil_lang::compile(
            "namespace test.call\ntrait Validatable { fn validate() -> bool }\nmessage Event { value @0 : bool }\nimpl Validatable for Event { fn validate() -> bool { return helper() } }",
        )
        .compiled
        .unwrap();
        assert!(matches!(
            generate(&compiled),
            Err(CodegenError::PortableFunction(
                vexil_lang::codegen::portable::PortableFunctionError::UnsupportedCall { .. }
            ))
        ));
    }

    #[test]
    fn project_codegen_qualifies_imported_trait() {
        use vexil_lang::codegen::CodegenBackend;
        use vexil_lang::resolve::InMemoryLoader;

        let root_src = "namespace proj.root\nimport { Tagged } from proj.dep\nmessage Event { tag @0 : u64 }\nimpl Tagged<u64> for Event { fn retag(tag: u64) -> u64 { self.tag = tag return self.tag } }";
        let dep_src = "namespace proj.dep\ntrait Tagged<T> { tag @0 : T fn retag(tag: T) -> T }";
        let mut loader = InMemoryLoader::new();
        loader.schemas.insert("proj.dep".into(), dep_src.into());
        let result = vexil_lang::compile_project(
            root_src,
            &std::path::PathBuf::from("proj/root.vexil"),
            &loader,
        )
        .unwrap();
        assert!(result.diagnostics.is_empty(), "{:?}", result.diagnostics);

        let files = crate::backend::GoBackend.generate_project(&result).unwrap();
        let root = files
            .iter()
            .find(|(path, _)| path.to_string_lossy().ends_with("root.go"))
            .map(|(_, code)| code)
            .unwrap();
        assert!(root.contains("\"proj/dep\""), "{root}");
        assert!(
            root.contains("var _ dep.Tagged[uint64] = (*Event)(nil)"),
            "{root}"
        );
        assert!(
            root.contains("func (m *Event) Retag(tag uint64) uint64"),
            "{root}"
        );
    }
}
